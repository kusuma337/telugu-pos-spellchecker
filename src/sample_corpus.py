def format_conll(sentences: list[list[tuple[str, str]]]) -> str:
    blocks = []
    for sentence in sentences:
        lines = [f"{word}\t{tag}" for word, tag in sentence]
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks) + "\n"


def write_sample_corpus(path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(format_conll(build_sample_sentences()), encoding="utf-8")
    return path
