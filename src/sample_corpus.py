def _sent(*words: str) -> list[tuple[str, str]]:
    tagged = []
    for word in words:
        if word not in LEXICON:
            raise KeyError(f"Word {word!r} is missing from the sample lexicon.")
        tagged.append((word, LEXICON[word]))
    return tagged


